#!/usr/bin/env node
/**
 * Writes .env.local from local Supabase instance.
 * Run after: pnpm db:start
 */
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const envPath = resolve(root, ".env.local");

function run(cmd) {
  return execSync(cmd, { cwd: root, encoding: "utf8" }).trim();
}

try {
  execSync("docker info", { stdio: "ignore" });
} catch {
  console.error("Docker is not running.");
  console.error("\nOption A — Start Docker Desktop, then:");
  console.error("  pnpm db:start && pnpm db:setup && pnpm db:migrate");
  console.error("\nOption B — Use Supabase Cloud (no Docker):");
  console.error("  pnpm doctor");
  process.exit(1);
}

try {
  const status = run("pnpm exec supabase status -o env");
  const vars = Object.fromEntries(
    status
      .split("\n")
      .filter((line) => line.includes("="))
      .map((line) => {
        const idx = line.indexOf("=");
        return [line.slice(0, idx), line.slice(idx + 1).replace(/^"|"$/g, "")];
      }),
  );

  const url = vars.API_URL ?? vars.SUPABASE_URL;
  const anonKey = vars.ANON_KEY ?? vars.SUPABASE_ANON_KEY;
  const serviceKey = vars.SERVICE_ROLE_KEY ?? vars.SUPABASE_SERVICE_ROLE_KEY;

  if (!url || !anonKey) {
    console.error("Could not read Supabase status. Is Docker running? Try: pnpm db:start");
    process.exit(1);
  }

  let existing = "";
  if (existsSync(envPath)) {
    existing = readFileSync(envPath, "utf8");
  }

  const lines = [
    "# Auto-generated by pnpm db:setup — local Supabase",
    `NEXT_PUBLIC_SUPABASE_URL=${url}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
    serviceKey ? `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}` : "",
    "",
    "# Optional: restrict signups to this email domain",
    existing.includes("ALLOWED_EMAIL_DOMAIN=")
      ? existing
          .split("\n")
          .find((l) => l.startsWith("ALLOWED_EMAIL_DOMAIN=")) ?? "ALLOWED_EMAIL_DOMAIN="
      : "ALLOWED_EMAIL_DOMAIN=",
    "",
  ].filter(Boolean);

  writeFileSync(envPath, lines.join("\n") + "\n");
  console.log("✓ Wrote .env.local with local Supabase credentials");
  console.log("  Next: pnpm db:migrate && pnpm seed && pnpm dev");
} catch (err) {
  console.error("Failed:", err instanceof Error ? err.message : err);
  console.error("\nMake sure Docker is running, then:");
  console.error("  pnpm db:start");
  console.error("  pnpm db:setup");
  process.exit(1);
}
